/* Turns inputs/1-scents.csv into data/scents.ts for the Scent Finder.

   Run:  npm run scents            (reads inputs/1-scents.csv)
         npm run scents -- path.csv

   Rows whose id starts with "example" are skipped.
   Multi-value cells (moods, places) use | between values; notes use ; between notes.
   Values must use the words in data/finder.ts:
     moods warm|calm|bold|soft   places forest|coast|study|city
     time_of_day morning|afternoon|dusk|night
     scent_family woody|floral|gourmand|amber|fresh
     intensity close|present|lingering
*/
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const src = resolve(process.argv[2] ?? 'inputs/1-scents.csv');
const out = resolve('data/scents.ts');

/** Minimal CSV parser: quoted fields, commas, and newlines inside quotes. */
function parseCsv(text: string): string[][] {
  const rows: string[][] = [];
  let row: string[] = [];
  let cell = '';
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') { cell += '"'; i++; }
      else if (c === '"') quoted = false;
      else cell += c;
    } else if (c === '"') quoted = true;
    else if (c === ',') { row.push(cell); cell = ''; }
    else if (c === '\n' || c === '\r') {
      if (c === '\r' && text[i + 1] === '\n') i++;
      row.push(cell); cell = '';
      if (row.some((v) => v.trim() !== '')) rows.push(row);
      row = [];
    } else cell += c;
  }
  row.push(cell);
  if (row.some((v) => v.trim() !== '')) rows.push(row);
  return rows;
}

const split = (v: string | undefined, sep: string) => (v ?? '').split(sep).map((x) => x.trim()).filter(Boolean);

const [header, ...body] = parseCsv(readFileSync(src, 'utf8').replace(/^﻿/, ''));
const col = (r: string[], name: string) => (r[header.indexOf(name)] ?? '').trim();

const scents = body
  .filter((r) => col(r, 'id') && !col(r, 'id').startsWith('example'))
  .map((r) => ({
    id: col(r, 'id'),
    name: col(r, 'name'),
    family: col(r, 'scent_family').toLowerCase(),
    top: split(col(r, 'top_notes'), ';').join(', '),
    heart: split(col(r, 'heart_notes'), ';').join(', '),
    base: split(col(r, 'base_notes'), ';').join(', '),
    moods: split(col(r, 'moods'), '|').map((m) => m.toLowerCase()),
    places: split(col(r, 'places'), '|').map((p) => p.toLowerCase()),
    time: col(r, 'time_of_day').toLowerCase(),
    intensity: col(r, 'intensity').toLowerCase(),
    description: col(r, 'short_description'),
    image: header.includes('image') ? col(r, 'image') : '',
  }));

writeFileSync(
  out,
  `import type { Scent } from '@/lib/types';\n\n` +
    `/* Generated by \`npm run scents\` from inputs/1-scents.csv. Do not edit by hand. */\n` +
    `export const scents: Scent[] = ${JSON.stringify(scents, null, 2)};\n`,
  'utf8',
);
console.log(`${scents.length} scents written to ${out}`);
