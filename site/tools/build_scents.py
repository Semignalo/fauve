"""Turn inputs/1-scents.csv into data/scents.js for the Scent Finder.

Run from the site folder:  python tools/build_scents.py ../inputs/1-scents.csv
Rows whose id starts with 'example' are skipped.
Multi-value cells (moods, places) use | between values; notes use ; between notes.
"""
import csv, json, sys, pathlib

src = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else '../inputs/1-scents.csv')
out = pathlib.Path(__file__).resolve().parent.parent / 'data' / 'scents.js'
rows = []
with src.open(newline='', encoding='utf-8') as f:
    for r in csv.DictReader(f):
        if not r.get('id') or r['id'].startswith('example'):
            continue
        split = lambda v, sep: [x.strip() for x in (v or '').split(sep) if x.strip()]
        rows.append({
            'id': r['id'].strip(), 'name': r['name'].strip(),
            'family': r['scent_family'].strip().lower(),
            'top': ', '.join(split(r['top_notes'], ';')),
            'heart': ', '.join(split(r['heart_notes'], ';')),
            'base': ', '.join(split(r['base_notes'], ';')),
            'moods': [m.lower() for m in split(r['moods'], '|')],
            'places': [p.lower() for p in split(r['places'], '|')],
            'time': r['time_of_day'].strip().lower(),
            'intensity': r['intensity'].strip().lower(),
            'description': r['short_description'].strip(),
            'image': r.get('image', '').strip()
        })
out.write_text('/* Generated by tools/build_scents.py from inputs/1-scents.csv. Do not edit by hand. */\n'
               'window.FAUVE_SCENTS = ' + json.dumps(rows, indent=2, ensure_ascii=False) + ';\n', encoding='utf-8')
print(f'{len(rows)} scents written to {out}')
